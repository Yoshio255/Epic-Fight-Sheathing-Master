package com.yoshio.epic_fight_sheathing_master;

import com.mojang.logging.LogUtils;
import net.minecraft.client.Minecraft;
import net.minecraft.server.packs.resources.ResourceManagerReloadListener;
import net.minecraft.world.item.Item;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.client.ConfigScreenHandler;
import net.minecraftforge.client.event.ClientPlayerNetworkEvent;
import net.minecraftforge.client.event.RegisterClientReloadListenersEvent;
import net.minecraftforge.common.MinecraftForge;
import net.minecraftforge.event.server.ServerStartingEvent;
import net.minecraftforge.eventbus.api.IEventBus;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.ModLoadingContext;
import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.fml.config.ModConfig;
import net.minecraftforge.fml.event.lifecycle.FMLClientSetupEvent;
import net.minecraftforge.fml.event.lifecycle.FMLCommonSetupEvent;
import net.minecraftforge.fml.javafmlmod.FMLJavaModLoadingContext;
import net.minecraftforge.registries.DeferredRegister;
import net.minecraftforge.registries.ForgeRegistries;
import net.minecraftforge.registries.RegistryObject;
import org.slf4j.Logger;

@Mod(Epic_fight_sheathing_master.MODID)
public class Epic_fight_sheathing_master {

    public static final String MODID = "epic_fight_sheathing_master";
    private static final Logger LOGGER = LogUtils.getLogger();

    public static final DeferredRegister<Item> ITEMS = DeferredRegister.create(ForgeRegistries.ITEMS, MODID);

    // Display-only item for the tachi's back/waist sheath, rendered manually by
    // PatchedItemInHandLayerMixin alongside the tachi blade. Never placed in an
    // inventory slot by normal gameplay.
    public static final RegistryObject<Item> TACHI_SHEATH = ITEMS.register("tachi_sheath",
            () -> new Item(new Item.Properties()));

    // Same as TACHI_SHEATH but with a carry-string texture, used for the
    // WAIST-mode display instead of TACHI_SHEATH.
    public static final RegistryObject<Item> TACHI_SHEATH_WITH_STRING = ITEMS.register("tachi_sheath_with_string",
            () -> new Item(new Item.Properties()));

    // Display-only item for the dagger's thigh sheath, rendered manually by
    // PatchedItemInHandLayerMixin at HumanoidArmature.thighR/thighL. Never
    // placed in an inventory slot by normal gameplay.
    public static final RegistryObject<Item> DAGGER_SHEATH = ITEMS.register("dagger_sheath",
            () -> new Item(new Item.Properties()));

    // Display-only item for the vanilla sword's waist/back sheath, rendered
    // manually by PatchedItemInHandLayerMixin at the Torso (WAIST) or Chest
    // (BACK) bone. Never placed in an inventory slot by normal gameplay.
    public static final RegistryObject<Item> SWORD_SHEATH = ITEMS.register("sword_sheath",
            () -> new Item(new Item.Properties()));

    // Display-only item for the longsword's waist/back sheath, same pattern
    // as SWORD_SHEATH. Never placed in an inventory slot by normal gameplay.
    public static final RegistryObject<Item> LONGSWORD_SHEATH = ITEMS.register("longsword_sheath",
            () -> new Item(new Item.Properties()));

    // Display-only tapered sheaths (Forge OBJ models, generated by tools/make_nf_sheath_obj.js)
    // for EFN's nf_shortsword / nf_shortsword_2, drawn by MeshWeaponIdleRenderer around the
    // 3D blade. Never placed in an inventory slot by normal gameplay.
    public static final RegistryObject<Item> NF_SHORTSWORD_SHEATH = ITEMS.register("nf_shortsword_sheath",
            () -> new Item(new Item.Properties()));
    public static final RegistryObject<Item> NF_SHORTSWORD_2_SHEATH = ITEMS.register("nf_shortsword_2_sheath",
            () -> new Item(new Item.Properties()));

    // Display-only 3D sheath (Forge OBJ model, generated by tools/make_evil_tachi_sheath_obj.js) for Weapons of
    // Miracles' Evil Tachi, drawn by PatchedItemInHandLayerMixin in the same frame as the blade. Never placed in an
    // inventory slot by normal gameplay.
    public static final RegistryObject<Item> EVIL_TACHI_SHEATH = ITEMS.register("evil_tachi_sheath",
            () -> new Item(new Item.Properties()));
    // Same sheath with a cord wound round it, used for the WAIST-mode display (as if tied to the belt).
    public static final RegistryObject<Item> EVIL_TACHI_SHEATH_WITH_BAND = ITEMS.register("evil_tachi_sheath_with_band",
            () -> new Item(new Item.Properties()));

    public Epic_fight_sheathing_master() {
        IEventBus modEventBus = FMLJavaModLoadingContext.get().getModEventBus();

        ITEMS.register(modEventBus);
        modEventBus.addListener(this::commonSetup);

        MinecraftForge.EVENT_BUS.register(this);
        MinecraftForge.EVENT_BUS.addListener(EfsmCommand::register);

        ModLoadingContext.get().registerConfig(ModConfig.Type.COMMON, Config.SPEC);
    }

    private void commonSetup(final FMLCommonSetupEvent event) {
    }

    @SubscribeEvent
    public void onServerStarting(ServerStartingEvent event) {
    }

    @Mod.EventBusSubscriber(modid = MODID, bus = Mod.EventBusSubscriber.Bus.MOD, value = Dist.CLIENT)
    public static class ClientModEvents {

        @SubscribeEvent
        public static void onClientSetup(FMLClientSetupEvent event) {

            // Read the sheath allowlist up front (creates the template file on
            // first run) so the first rendered frame doesn't do file I/O.
            SheathAllowlist.reload();

            ModLoadingContext.get().registerExtensionPoint(ConfigScreenHandler.ConfigScreenFactory.class,
                    () -> new ConfigScreenHandler.ConfigScreenFactory((mc, screen) -> new EfsmConfigScreen(screen)));
        }

        // After every resource (re)load — resource packs may have changed the vanilla
        // textures the automatic allow check compares against — forget its results.
        @SubscribeEvent
        public static void onRegisterReloadListeners(RegisterClientReloadListenersEvent event) {
            event.registerReloadListener((ResourceManagerReloadListener) resourceManager -> SheathAllowlist.clearCaches());
        }
    }

    // Epic Fight's item data (weapon categories) arrives after joining a world:
    // forget automatic allow results from before it.
    @Mod.EventBusSubscriber(modid = MODID, value = Dist.CLIENT)
    public static class ClientForgeEvents {

        @SubscribeEvent
        public static void onLoggingIn(ClientPlayerNetworkEvent.LoggingIn event) {
            SheathAllowlist.clearCaches();
        }
    }
}
